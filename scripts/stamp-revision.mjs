import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const GIT_SHA_RE = /^[0-9a-f]{7,40}$/i;
export const BAKED_REVISION_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/baked-revision.ts",
);

export function bakedRevisionSource(sha) {
  return `/** Generated by scripts/stamp-revision.mjs. The committed value is empty. */\nexport const BAKED_REVISION = ${JSON.stringify(sha)};\n`;
}

export const EMPTY_BAKED_REVISION_SOURCE = bakedRevisionSource("");

export function resolveGitSha() {
  const fromCi = process.env.WORKERS_CI_COMMIT_SHA?.trim() ?? "";
  if (GIT_SHA_RE.test(fromCi)) return fromCi.toLowerCase();
  try {
    const fromGit = execSync("git rev-parse HEAD", { encoding: "utf8" }).trim();
    if (GIT_SHA_RE.test(fromGit)) return fromGit.toLowerCase();
  } catch {
    // local install without git should not fail npm
  }
  return "";
}

export function stampRevision(sha = resolveGitSha()) {
  writeFileSync(BAKED_REVISION_PATH, bakedRevisionSource(sha));
  return sha;
}

const invokedDirectly =
  Boolean(process.argv[1]) &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  stampRevision();
}
